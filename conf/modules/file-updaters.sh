    # Update index.html with the new favicon (no changes needed, just confirming path)
    # The href="/favicon.ico" in index.html already points to the correct location
    
    echo -e "${GREEN}Favicon (.ico) updated in src/ directory${NC}"
}

# Updates production.sh script
update_production_script() {
    [[ "$CONFIGURE_PRODUCTION" != "true" ]] && return
    
    echo -e "${YELLOW}Updating $PRODUCTION_SCRIPT...${NC}"
    
    cat > "$PRODUCTION_SCRIPT" << 'EOF'
#!/bin/bash

# Production Deployment Configuration
# Note: Only DOMAIN and EMAIL are customizable during setup
# PROJECT_NAME, NETWORK_NAME, and PROJECT_PATH are static values
PROJECT_NAME="PROD_CONTAINER_NAME_PLACEHOLDER"
NETWORK_NAME="PROD_NETWORK_NAME_PLACEHOLDER"
DOMAIN="PROD_DOMAIN_PLACEHOLDER"
EMAIL="PROD_EMAIL_PLACEHOLDER"
PROJECT_PATH="PROD_PROJECT_PATH_PLACEHOLDER"

source "$(dirname "$0")/dependencies.sh"
cd "$PROJECT_PATH";
docker build -t nginx .; 
docker run --name "$PROJECT_NAME" -d \
  --network "$NETWORK_NAME" \
  -p 80:80 -p 443:443 \
  -e DOMAIN="$DOMAIN" \
  -e EMAIL="$EMAIL" \
  -v /etc/letsencrypt:/etc/letsencrypt \
  nginx;
EOF

    # Replace placeholders
    sed -i "s/PROD_CONTAINER_NAME_PLACEHOLDER/$PROD_CONTAINER_NAME/g" "$PRODUCTION_SCRIPT"
    sed -i "s/PROD_NETWORK_NAME_PLACEHOLDER/$PROD_NETWORK_NAME/g" "$PRODUCTION_SCRIPT"
    sed -i "s|PROD_DOMAIN_PLACEHOLDER|$PROD_DOMAIN|g" "$PRODUCTION_SCRIPT"
    sed -i "s|PROD_EMAIL_PLACEHOLDER|$PROD_EMAIL|g" "$PRODUCTION_SCRIPT"
    sed -i "s|PROD_PROJECT_PATH_PLACEHOLDER|$PROD_PROJECT_PATH|g" "$PRODUCTION_SCRIPT"
    
    chmod +x "$PRODUCTION_SCRIPT"
}

