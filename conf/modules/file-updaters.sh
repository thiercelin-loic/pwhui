# Updates styles.css with custom colors and background image
update_styles() {
    [[ "$CUSTOMIZE_COLORS" != "true" ]] && [[ "$CUSTOMIZE_BACKGROUND" != "true" ]] && return
    
    echo -e "${YELLOW}Updating $STYLES_FILE with custom theme...${NC}"
    
    # Remove existing custom theme section if present
    perl -i -0pe 's/\n*\/\* Custom Theme Colors - Generated by setup script \*\/.*?^}/\n/ms' "$STYLES_FILE"
    
    # Remove trailing empty lines at the end of file
    sed -i -e :a -e '/^\s*$/d;N;ba' "$STYLES_FILE"
    
    # Build custom theme CSS
    cat >> "$STYLES_FILE" << EOF


/* Custom Theme Colors - Generated by setup script */
:root {
EOF
    
    # Add color customizations if enabled
    if [[ "$CUSTOMIZE_COLORS" == "true" ]]; then
        cat >> "$STYLES_FILE" << EOF
  --primary: $THEME_PRIMARY_COLOR;
  --secondary: $THEME_SECONDARY_COLOR;
  --danger: #ff0000;
  --text: $THEME_TEXT_COLOR;
EOF
    fi
    
    # Add background image customization if enabled
    if [[ "$CUSTOMIZE_BACKGROUND" == "true" ]]; then
        cat >> "$STYLES_FILE" << EOF
  --background-image: url('$THEME_BACKGROUND_IMAGE');
EOF
    fi
    
    # Close the :root selector
    cat >> "$STYLES_FILE" << EOF
}
EOF
}

# Updates branding icons
