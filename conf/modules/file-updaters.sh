#!/bin/bash

# File Update Functions
# Applies configuration changes to project files

# Updates app.config.ts with configuration
update_app_config() {
    echo -e "${YELLOW}Updating $ENV_CONFIG_FILE...${NC}"
    
    cat > "$ENV_CONFIG_FILE" << EOF
/**
 * Application Configuration
 * 
 * This file contains all project-specific configuration values.
 * Modify these values to adapt the application for different contexts.
 */

export const APP_CONFIG = {
  /**
   * Application branding and metadata
   */
  name: '$APP_NAME',
  title: '$APP_TITLE',
  description: '$APP_DESCRIPTION',
  
  /**
   * Project context and identification
   * Used for licensing, attribution, and analytics
   */
  project: {
    name: '$PROJECT_NAME',
    displayName: '$APP_TITLE',
    domain: '$PROJECT_DOMAIN',
    url: '$PROJECT_URL',
  },
  
  /**
   * Backend API configuration
   * Defines endpoints for each microservice
   */
  api: {
    auth: {
      host: '$AUTH_HOST',
      port: $AUTH_PORT,
      protocol: '$AUTH_PROTOCOL',
    },
    booking: {
      host: '$BOOKING_HOST',
      port: $BOOKING_PORT,
      protocol: '$BOOKING_PROTOCOL',
    },
    messaging: {
      host: '$MESSAGING_HOST',
      port: $MESSAGING_PORT,
      protocol: '$MESSAGING_PROTOCOL',
    },
  },
  
  /**
   * Feature flags
   * Enable/disable major application features
   */
  features: {
    auth: $FEATURE_AUTH,
    booking: $FEATURE_BOOKING,
    messaging: $FEATURE_MESSAGING,
    i18n: $FEATURE_I18N,
    policies: $FEATURE_POLICIES,
  },
  
  /**
   * UI/UX preferences
   */
  ui: {
    defaultLanguage: '$UI_DEFAULT_LANG',
    availableLanguages: ['$(echo "$UI_AVAILABLE_LANGS" | sed "s/,/', '/g")'],
    dateFormat: '$UI_DATE_FORMAT',
    timeFormat: '$UI_TIME_FORMAT',
  },
  
  /**
   * License information
   */
  license: '$PROJECT_LICENSE',
} as const;

/**
 * Helper function to construct full API URLs
 */
export function getApiUrl(service: 'auth' | 'booking' | 'messaging'): string {
  const config = APP_CONFIG.api[service];
  return \`\${config.protocol}://\${config.host}:\${config.port}\`;
}

/**
 * Export computed values for easy access
 */
export const API_BASE_URLS = {
  AUTH: getApiUrl('auth'),
  BOOKING: getApiUrl('booking'),
  MESSAGING: getApiUrl('messaging'),
} as const;
EOF
}

