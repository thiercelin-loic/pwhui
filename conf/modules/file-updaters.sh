}

# Updates package.json name
update_package_json() {
    echo -e "${YELLOW}Updating $PACKAGE_FILE name...${NC}"
    local lowercase_name
    lowercase_name=$(echo "$APP_NAME" | tr '[:upper:]' '[:lower:]' | tr ' ' '-')
    
    # Use a more robust method to update package.json
    # This is a simple sed approach - consider using jq for production
    sed -i "s/\"name\": \".*\"/\"name\": \"$lowercase_name\"/g" "$PACKAGE_FILE"
}

# Applies all configuration changes
apply_configuration() {
    echo ""
    echo -e "${BLUE}Applying configuration changes...${NC}"
    echo ""
    
    update_app_config
    update_proxy_config
    update_styles
    update_favicon
    update_production_script
    update_nginx_config
    update_entrypoint_script
    update_cookie_constants
    update_animation_constants
    update_message_constants
    update_index_html
    update_package_json
    
    echo ""
    echo -e "${GREEN}All configuration files updated successfully!${NC}"
}
